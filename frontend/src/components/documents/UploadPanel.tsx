"use client";

import Link from "next/link";
import { useCallback, useEffect, useId, useRef, useState, type DragEvent } from "react";

import { api } from "@/lib/client";
import { COMING_SOON_EXTENSIONS, MAX_UPLOAD_MB, SUPPORTED_EXTENSIONS } from "@/lib/config";
import { JURISDICTION_LABEL, STATUS_LABEL } from "@/lib/labels";
import { ApiError, isDuplicate, toProblem } from "@/lib/problem";
import { formatBytes } from "@/lib/text";
import { TOPIC_OPTIONS } from "@/lib/topics";
import type { DocumentOut, Jurisdiction } from "@/lib/types";

import { useToast } from "../Toast";
import { Badge, Button, Spinner, cx } from "../ui";

type EntryState = "queued" | "uploading" | "processing" | "ready" | "failed" | "duplicate" | "rejected";

type Entry = {
  key: string;
  file: File;
  state: EntryState;
  message?: string;
  docId?: string;
  existingId?: string;
  progress?: string;
};

const TERMINAL_DOC = new Set(["READY", "READY_STALE", "FAILED"]);
const POLL_MS = 2000;
const POLL_LIMIT = 150; // ~5 minutes

/** `local_only` keeps private context on the local model (blueprint §3.7); the notice changes with it. */
const POLICY = process.env.NEXT_PUBLIC_PRIVATE_CONTEXT_POLICY === "local_only" ? "local_only" : "hosted_with_notice";

function ext(name: string): string {
  const i = name.lastIndexOf(".");
  return i < 0 ? "" : name.slice(i + 1).toLowerCase();
}

function precheck(file: File): { state: EntryState; message?: string } {
  const e = ext(file.name);
  if ((COMING_SOON_EXTENSIONS as readonly string[]).includes(e)) {
    return { state: "rejected", message: `.${e} support is coming soon. Convert it to PDF for now.` };
  }
  if (!(SUPPORTED_EXTENSIONS as readonly string[]).includes(e)) {
    return { state: "rejected", message: `.${e || "?"} is not an accepted type.` };
  }
  if (file.size === 0) return { state: "rejected", message: "The file is empty." };
  if (file.size > MAX_UPLOAD_MB * 1024 * 1024) {
    return { state: "rejected", message: `Larger than ${MAX_UPLOAD_MB} MB.` };
  }
  return { state: "queued" };
}

const STATE_VIEW: Record<EntryState, { label: string; tone: "neutral" | "info" | "ok" | "bad" | "warn" }> = {
  queued: { label: "Queued", tone: "neutral" },
  uploading: { label: "Uploading", tone: "info" },
  processing: { label: "Processing", tone: "info" },
  ready: { label: "Ready", tone: "ok" },
  failed: { label: "Failed", tone: "bad" },
  duplicate: { label: "Duplicate", tone: "warn" },
  rejected: { label: "Not uploaded", tone: "bad" },
};

export function PrivacyNotice() {
  return (
    <div className="rounded-lg border border-mine/40 bg-mine/10 p-3 text-sm text-fg">
      <p className="font-semibold text-mine">Before you upload: how your files are used</p>
      {POLICY === "hosted_with_notice" ? (
        <ul className="mt-1 list-disc space-y-0.5 ps-5">
          <li>
            Answers that use your uploads are generated by a hosted model (OpenAI API). The passages from your files
            that match a question are sent to OpenAI and processed under its API terms, and those answers carry a
            notice saying so.
          </li>
          <li>Your uploads are private: other users cannot search or see them. Official sources are public government material.</li>
          <li>Do not upload files with personal data (CNIC numbers, phone numbers, addresses) that you may not share.</li>
          <li>You can delete an upload at any time; its text is removed from search immediately.</li>
        </ul>
      ) : (
        <ul className="mt-1 list-disc space-y-0.5 ps-5">
          <li>
            Answers that use your uploads are generated by a local model on this server. Nothing from your files is
            sent to a hosted model, so those answers may be lower quality and are marked as degraded.
          </li>
          <li>Your uploads are private: other users cannot search or see them.</li>
          <li>You can delete an upload at any time; its text is removed from search immediately.</li>
        </ul>
      )}
    </div>
  );
}

export function UploadPanel({
  isAdmin,
  onDocument,
}: {
  isAdmin: boolean;
  /** Called with each created or updated document so the table can show it. */
  onDocument: (doc: DocumentOut) => void;
}) {
  const toast = useToast();
  const [entries, setEntries] = useState<Entry[]>([]);
  const [acknowledged, setAcknowledged] = useState(false);
  const [dragging, setDragging] = useState(false);
  const [meta, setMeta] = useState<{ agency: string; jurisdiction: Jurisdiction | ""; topic: string; effective_date: string }>({
    agency: "",
    jurisdiction: "",
    topic: "",
    effective_date: "",
  });
  const [official, setOfficial] = useState(false);
  const running = useRef(false);
  const inputRef = useRef<HTMLInputElement>(null);
  const ids = { ack: useId(), input: useId(), agency: useId(), prov: useId(), topic: useId(), date: useId(), hint: useId() };

  const update = useCallback((key: string, patch: Partial<Entry>) => {
    setEntries((es) => es.map((e) => (e.key === key ? { ...e, ...patch } : e)));
  }, []);

  const addFiles = (files: FileList | File[]) => {
    const list = Array.from(files);
    if (list.length === 0) return;
    setEntries((es) => [
      ...list.map((file, i) => ({ key: `${Date.now()}-${i}-${file.name}`, file, ...precheck(file) })),
      ...es,
    ]);
  };

  const poll = useCallback(
    async (key: string, docId: string) => {
      for (let i = 0; i < POLL_LIMIT; i++) {
        await new Promise((r) => setTimeout(r, POLL_MS));
        try {
          const doc = await api.getDocument(docId);
          onDocument(doc);
          if (doc.progress) update(key, { progress: `${doc.progress.pages_done}/${doc.progress.pages_total} pages` });
          if (TERMINAL_DOC.has(doc.status)) {
            update(key, {
              state: doc.status === "FAILED" ? "failed" : "ready",
              message: doc.status === "FAILED" ? (doc.error ?? "Ingestion failed.") : `${doc.chunk_count ?? 0} chunks indexed`,
              progress: undefined,
            });
            return;
          }
        } catch (err) {
          if (err instanceof ApiError && err.status === 404) {
            update(key, { state: "failed", message: "The document disappeared (deleted?)." });
            return;
          }
          // transient: keep polling
        }
      }
      update(key, { message: "Still processing. Refresh the list later." });
    },
    [onDocument, update],
  );

  // Upload queued entries one at a time.
  useEffect(() => {
    if (running.current) return;
    const next = entries.findLast((e) => e.state === "queued");
    if (!next) return;
    running.current = true;
    update(next.key, { state: "uploading", message: undefined });
    api
      .uploadDocument(next.file, {
        visibility: isAdmin && official ? "public" : "private",
        agency: meta.agency.trim() || undefined,
        jurisdiction: meta.jurisdiction || undefined,
        topic: meta.topic.trim() || undefined,
        effective_date: meta.effective_date || undefined,
      })
      .then((doc) => {
        onDocument(doc);
        if (TERMINAL_DOC.has(doc.status)) {
          update(next.key, {
            state: doc.status === "FAILED" ? "failed" : "ready",
            docId: doc.id,
            message: doc.status === "FAILED" ? (doc.error ?? "Ingestion failed.") : `${doc.chunk_count ?? 0} chunks indexed`,
          });
        } else {
          update(next.key, { state: "processing", docId: doc.id, message: STATUS_LABEL[doc.status] });
          void poll(next.key, doc.id);
        }
      })
      .catch((err: unknown) => {
        const e = err instanceof ApiError ? err : new ApiError(toProblem(0, { code: "client_error", title: "Upload failed", detail: String(err) }));
        if (isDuplicate(e)) {
          const existing = typeof e.extra.existing_document_id === "string" ? e.extra.existing_document_id : undefined;
          update(next.key, { state: "duplicate", message: e.detail, existingId: existing });
          toast({
            tone: "warn",
            title: e.title,
            detail: e.detail,
            link: existing ? { href: `/documents?doc=${encodeURIComponent(existing)}`, label: "View the existing document" } : undefined,
          });
        } else {
          update(next.key, { state: "failed", message: `${e.title}: ${e.detail}` });
        }
      })
      .finally(() => {
        running.current = false;
        // Trigger the effect again for the next queued file.
        setEntries((es) => [...es]);
      });
  }, [entries, isAdmin, official, meta, onDocument, poll, toast, update]);

  const onDrop = (e: DragEvent) => {
    e.preventDefault();
    setDragging(false);
    if (!acknowledged) return;
    addFiles(e.dataTransfer.files);
  };

  const active = entries.filter((e) => e.state === "queued" || e.state === "uploading" || e.state === "processing").length;
  const accept = SUPPORTED_EXTENSIONS.map((x) => `.${x}`).join(",");

  return (
    <section aria-labelledby={`${ids.input}-h`} className="flex flex-col gap-3 rounded-xl border border-border bg-surface p-4">
      <h2 id={`${ids.input}-h`} className="font-semibold">
        Upload documents
      </h2>
      <PrivacyNotice />
      <label htmlFor={ids.ack} className="flex items-start gap-2 text-sm">
        <input
          id={ids.ack}
          type="checkbox"
          checked={acknowledged}
          onChange={(e) => setAcknowledged(e.target.checked)}
          className="mt-1 h-4 w-4 accent-[var(--accent)]"
        />
        <span>I have read how my uploads are processed.</span>
      </label>

      <details className="rounded-md border border-border px-3 py-2 text-sm">
        <summary className="cursor-pointer font-medium">Metadata for this batch (optional)</summary>
        <div className="mt-2 grid gap-2 sm:grid-cols-2">
          <div className="flex flex-col gap-1">
            <label htmlFor={ids.agency} className="text-xs font-medium text-muted">
              Agency
            </label>
            <input
              id={ids.agency}
              value={meta.agency}
              maxLength={80}
              onChange={(e) => setMeta({ ...meta, agency: e.target.value })}
              placeholder="e.g. DGIP"
              className="rounded-md border border-border bg-bg px-2 py-1 text-fg"
            />
          </div>
          <div className="flex flex-col gap-1">
            <label htmlFor={ids.prov} className="text-xs font-medium text-muted">
              Province
            </label>
            <select
              id={ids.prov}
              value={meta.jurisdiction}
              onChange={(e) => setMeta({ ...meta, jurisdiction: e.target.value as Jurisdiction | "" })}
              className="rounded-md border border-border bg-bg px-2 py-1 text-fg"
            >
              <option value="">Not set</option>
              {(Object.keys(JURISDICTION_LABEL) as Jurisdiction[]).map((j) => (
                <option key={j} value={j}>
                  {JURISDICTION_LABEL[j]}
                </option>
              ))}
            </select>
          </div>
          <div className="flex flex-col gap-1">
            <label htmlFor={ids.topic} className="text-xs font-medium text-muted">
              Topic
            </label>
            {isAdmin && official ? (
              <select
                id={ids.topic}
                value={meta.topic}
                onChange={(e) => setMeta({ ...meta, topic: e.target.value })}
                className="rounded-md border border-border bg-bg px-2 py-1 text-fg"
              >
                <option value="">Detect automatically</option>
                {TOPIC_OPTIONS.map((o) => (
                  <option key={o.value} value={o.value}>
                    {o.label}
                  </option>
                ))}
              </select>
            ) : (
              <input
                id={ids.topic}
                value={meta.topic}
                maxLength={60}
                onChange={(e) => setMeta({ ...meta, topic: e.target.value })}
                placeholder="e.g. passport"
                className="rounded-md border border-border bg-bg px-2 py-1 text-fg"
              />
            )}
          </div>
          <div className="flex flex-col gap-1">
            <label htmlFor={ids.date} className="text-xs font-medium text-muted">
              Effective date
            </label>
            <input
              id={ids.date}
              type="date"
              value={meta.effective_date}
              onChange={(e) => setMeta({ ...meta, effective_date: e.target.value })}
              className="rounded-md border border-border bg-bg px-2 py-1 text-fg"
            />
          </div>
        </div>
      </details>

      {isAdmin && (
        <label className="flex items-center gap-2 text-sm">
          <input
            type="checkbox"
            checked={official}
            onChange={(e) => setOfficial(e.target.checked)}
            className="h-4 w-4 accent-[var(--accent)]"
          />
          <span>
            Add to <strong>official sources</strong> (visible to every user)
          </span>
        </label>
      )}

      <label
        htmlFor={ids.input}
        onDragOver={(e) => {
          e.preventDefault();
          if (acknowledged) setDragging(true);
        }}
        onDragLeave={() => setDragging(false)}
        onDrop={onDrop}
        aria-disabled={!acknowledged}
        className={cx(
          "flex flex-col items-center justify-center gap-1 rounded-lg border-2 border-dashed px-4 py-6 text-center text-sm has-[:focus-visible]:outline-2 has-[:focus-visible]:outline-offset-2 has-[:focus-visible]:outline-[var(--focus)]",
          !acknowledged
            ? "cursor-not-allowed border-border text-muted"
            : dragging
              ? "cursor-copy border-accent bg-accent/10 text-fg"
              : "cursor-pointer border-border text-fg hover:border-accent",
        )}
      >
        <input
          ref={inputRef}
          id={ids.input}
          type="file"
          multiple
          accept={accept}
          disabled={!acknowledged}
          aria-describedby={ids.hint}
          className="sr-only"
          onChange={(e) => {
            if (e.target.files) addFiles(e.target.files);
            e.target.value = "";
          }}
        />
        <span className="font-medium">
          {acknowledged ? "Drop files here or choose files" : "Tick the box above to enable uploads"}
        </span>
        <span id={ids.hint} className="text-xs text-muted">
          PDF, DOCX, HTML, TXT, MD · up to {MAX_UPLOAD_MB} MB each · PPTX, JPG and PNG coming soon
        </span>
      </label>

      {entries.length > 0 && (
        <div>
          <div className="flex items-center justify-between">
            <p className="text-sm font-medium" aria-live="polite">
              {active > 0 ? `${active} file${active === 1 ? "" : "s"} in progress` : "All uploads finished"}
            </p>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => setEntries((es) => es.filter((e) => ["queued", "uploading", "processing"].includes(e.state)))}
            >
              Clear finished
            </Button>
          </div>
          <ul className="mt-1 flex flex-col gap-1" aria-label="Upload status">
            {entries.map((e) => {
              const view = STATE_VIEW[e.state];
              const busy = e.state === "uploading" || e.state === "processing";
              return (
                <li key={e.key} className="flex flex-wrap items-center gap-2 rounded-md border border-border px-2 py-1.5 text-sm">
                  <Badge tone={view.tone}>
                    {busy && <Spinner small />}
                    {view.label}
                  </Badge>
                  <span className="min-w-0 flex-1 break-all" dir="auto">
                    {e.file.name}
                  </span>
                  <span className="text-xs text-muted">{formatBytes(e.file.size)}</span>
                  {(e.message || e.progress) && (
                    <span className="basis-full text-xs text-muted" dir="auto">
                      {[e.progress, e.message].filter(Boolean).join(" · ")}
                      {e.existingId && (
                        <>
                          {" "}
                          <Link
                            href={`/documents?doc=${encodeURIComponent(e.existingId)}`}
                            className="font-medium text-accent underline underline-offset-2"
                          >
                            View existing
                          </Link>
                        </>
                      )}
                    </span>
                  )}
                </li>
              );
            })}
          </ul>
        </div>
      )}
    </section>
  );
}
